// Built-in categories are known by their key, never by their translated name
const byKey = {
  food: 'utensils',
  transport: 'bus',
  bills: 'receipt',
  fun: 'partyPopper',
  uncategorized: 'circleDashed',
}

// A bare Lucide icon in the colour of the text around it (24x24 grid, stroke 2
// unless another is asked for)
export function Icon({ name, size = 20, stroke = 2 }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={stroke}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {paths[name]}
    </svg>
  )
}

// First character of a custom name when it is a letter (any alphabet), in
// capitals; null when it is a symbol, an emoji or there is no name
function firstLetter(name) {
  const first = Array.from(name.trim())[0]
  return first && /\p{L}/u.test(first) ? first.toUpperCase() : null
}

// Round icon with a soft background and the colour of the category.
//   category: a category object, or undefined (uncategorized)
//   kind: 'income' | 'savings' | 'savingsOut' to show those icons instead
//   source: an income source ('salary', 'freelance', 'gift', 'other'); with
//     kind 'income' it picks that source's icon and colour
//   size: 36 (rows) or 44 (bigger spots)
// Custom categories (they have a name) show the first letter of the name, or
// a tag when it does not start with a letter. The icon is decorative: the text
// next to it always names the category.
// Icon and colour of each income source (no source: the plain income icon)
const SOURCE_LOOK = {
  salary: ['briefcase', 'var(--income)', 'var(--accent-soft)'],
  freelance: ['laptop', 'var(--cat-blue)', 'var(--cat-blue-soft)'],
  gift: ['gift', 'var(--cat-fuchsia)', 'var(--cat-fuchsia-soft)'],
  other: ['coins', 'var(--cat-slate)', 'var(--cat-slate-soft)'],
}

export default function CategoryIcon({ category, kind, source, size = 36 }) {
  const inner = size > 36 ? 24 : 20
  let color = 'var(--cat-slate)'
  let soft = 'var(--cat-slate-soft)'
  let content = <Icon name="circleDashed" size={inner} />

  if (kind === 'income' && SOURCE_LOOK[source]) {
    const [icon, sourceColor, sourceSoft] = SOURCE_LOOK[source]
    color = sourceColor
    soft = sourceSoft
    content = <Icon name={icon} size={inner} />
  } else if (kind === 'income') {
    color = 'var(--income)'
    soft = 'var(--accent-soft)'
    content = <Icon name="handCoins" size={inner} />
  } else if (kind === 'savings') {
    color = 'var(--accent)'
    soft = 'var(--accent-soft)'
    content = <Icon name="piggyBank" size={inner} />
  } else if (kind === 'savingsOut') {
    color = 'var(--accent)'
    soft = 'var(--accent-soft)'
    content = <Icon name="arrowUpRight" size={inner} />
  } else if (category) {
    color = categoryColor(category)
    soft = `var(--cat-${category.color}-soft)`
    if (typeof category.name === 'string') {
      const letter = firstLetter(category.name)
      content = letter ? (
        <span className="cat-icon-letter">{letter}</span>
      ) : (
        <Icon name="tag" size={inner} />
      )
    } else if (byKey[category.key]) {
      content = <Icon name={byKey[category.key]} size={inner} />
    }
  }

  return (
    <span
      className={size > 36 ? 'cat-icon is-large' : 'cat-icon'}
      style={{ '--c': color, '--c-soft': soft }}
      aria-hidden="true"
    >
      {content}
    </span>
  )
}
